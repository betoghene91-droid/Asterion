// Generate src/ui/embed.ts from the Mini App's frontend sources in app/ui/.
//
// Why this exists: the Worker has no filesystem. Without an embed the Mini App
// route would have nothing to send and the whole console would be a 500 in
// production while every local test passed - exactly the failure mode
// skills-embed.ts was written to close for the skill packs. So the frontend is
// committed as data, by the same pattern:
//
//   app/ui/<file>  ->  (this script)  ->  src/ui/embed.ts   (regenerated, committed)
//
// Deterministic by construction: a fixed file order, no timestamps, no glob
// traversal order to depend on. Running it twice on unchanged sources produces a
// byte-identical file, which `tests/ui-embed.test.mjs` asserts.
//
// Usage:
//   node scripts/build-ui-embed.mjs           # write src/ui/embed.ts
//   node scripts/build-ui-embed.mjs --check   # exit 1 if it is out of date
//
// NOTE: never write a literal slash-star-star-slash sequence in a comment here;
// it terminates the block comment.

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const app = join(here, '..');
const uiDir = join(app, 'ui');
const out = join(app, 'src', 'ui', 'embed.ts');

/**
 * The shipped set, in a fixed order. `name` is also the lookup key the router
 * uses, and it is the ONLY thing that can select a file - there is no path join
 * on the request path anywhere, so traversal has nothing to act on.
 */
export const UI_FILES = [
  { name: 'index.html', file: 'index.html', contentType: 'text/html; charset=utf-8' },
  { name: 'ui.css', file: 'ui.css', contentType: 'text/css; charset=utf-8' },
  { name: 'ui.js', file: 'ui.js', contentType: 'text/javascript; charset=utf-8' },
];

/** Read the sources. Exported so the test can build the same map from disk. */
export function readSources(dir = uiDir) {
  return UI_FILES.map((f) => {
    const body = readFileSync(join(dir, f.file), 'utf8');
    return { name: f.name, contentType: f.contentType, body, bytes: Buffer.byteLength(body, 'utf8') };
  });
}

/** Render src/ui/embed.ts. Pure: same assets in, same string out. */
export function renderEmbed(assets) {
  const q = (s) => JSON.stringify(s);
  const lines = [];
  lines.push('/**');
  lines.push(' * GENERATED by scripts/build-ui-embed.mjs - do not edit by hand.');
  lines.push(' *');
  lines.push(' * Embedded copy of the Mini App frontend, so the deployed Worker (which has');
  lines.push(' * no filesystem) can serve the console from its own origin. Regenerate with:');
  lines.push(' *   node scripts/build-ui-embed.mjs');
  lines.push(' *');
  lines.push(' * Sources live in app/ui/. Served by src/ui/shell.ts at /ui, /ui/ui.css and');
  lines.push(' * /ui/ui.js.');
  lines.push(' */');
  lines.push('');
  lines.push('export interface UiAsset {');
  lines.push('  /** Lookup key AND served filename. Never a path. */');
  lines.push('  name: string;');
  lines.push('  contentType: string;');
  lines.push('  body: string;');
  lines.push('  bytes: number;');
  lines.push('}');
  lines.push('');
  lines.push('export const UI_ASSETS: UiAsset[] = [');
  for (const a of assets) {
    lines.push('  {');
    lines.push('    name: ' + q(a.name) + ',');
    lines.push('    contentType: ' + q(a.contentType) + ',');
    lines.push('    bytes: ' + a.bytes + ',');
    lines.push('    body: ' + q(a.body) + ',');
    lines.push('  },');
  }
  lines.push('];');
  lines.push('');
  return lines.join('\n');
}

function main() {
  const check = process.argv.includes('--check');

  for (const f of UI_FILES) {
    if (!existsSync(join(uiDir, f.file))) {
      console.error('ERROR missing source: app/ui/' + f.file);
      process.exit(1);
    }
  }

  const assets = readSources();
  const next = renderEmbed(assets);
  const total = assets.reduce((n, a) => n + a.bytes, 0);

  if (check) {
    const current = existsSync(out) ? readFileSync(out, 'utf8') : '';
    if (current !== next) {
      console.error('OUT OF DATE: run `node scripts/build-ui-embed.mjs`');
      process.exit(1);
    }
    console.log('embed is up to date (' + assets.length + ' asset(s), ' + total + ' bytes)');
    return;
  }

  writeFileSync(out, next);
  console.log(
    'wrote ' +
      out +
      ' with ' +
      assets.length +
      ' asset(s), ' +
      total +
      ' bytes (' +
      assets.map((a) => a.name + ' ' + a.bytes).join(', ') +
      ')',
  );
}

// Only run the CLI when invoked directly, so importing renderEmbed from a test
// does not rewrite the tree as a side effect.
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
