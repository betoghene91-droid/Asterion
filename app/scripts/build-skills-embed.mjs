// Generate src/skills-embed.ts from the skills catalog.
//
// Why this exists: the Worker has no filesystem, so skills.ts would load ZERO
// packs in production and every hunt would run skill-blind. skills.ts degrades
// gracefully in that case (correct - it must not throw), but degrading to
// nothing is still nothing. This closes the gap the same way playbooks.ts is
// closed: commit the content as data.
//
// Deterministic: sorted by id, stable key order, no timestamps.
// NOTE: never write a literal slash-star-star-slash sequence in a comment here;
// it terminates the block comment. Spell paths as <id> instead of a glob.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, '..', '..');
const skillsDir = join(repo, 'skills');
const out = join(here, '..', 'src', 'skills-embed.ts');

const REQUIRED = ['id','version','name','cls','family','requires','questions','false_positives','poc_must_show','impact_bar'];

const dirs = readdirSync(skillsDir, { withFileTypes: true })
  .filter((e) => e.isDirectory())
  .map((e) => e.name)
  .sort();

const packs = [];
for (const dir of dirs) {
  const file = join(skillsDir, dir, 'skill.json');
  let raw;
  try {
    raw = readFileSync(file, 'utf8');
  } catch {
    continue;
  }
  const meta = JSON.parse(raw);
  const missing = REQUIRED.filter((k) => !(k in meta));
  if (missing.length) {
    console.error('ERROR ' + dir + ': missing ' + missing.join(','));
    process.exitCode = 1;
    continue;
  }
  let body = '';
  try {
    body = readFileSync(join(skillsDir, dir, 'SKILL.md'), 'utf8');
  } catch {
    body = '';
  }
  packs.push({ meta, body });
}

const q = (s) => JSON.stringify(s);
const list = (a) => '[' + a.map(q).join(', ') + ']';

const lines = [];
lines.push('/**');
lines.push(' * GENERATED by scripts/build-skills-embed.mjs - do not edit by hand.');
lines.push(' *');
lines.push(' * Embedded copy of the skill catalog, so the deployed Worker (which has');
lines.push(' * no filesystem) still carries its hunting methodology. Regenerate with:');
lines.push(' *   node scripts/build-skills-embed.mjs');
lines.push(' */');
lines.push('');
lines.push('export interface EmbeddedSkill {');
lines.push('  meta: Record<string, unknown>;');
lines.push('  body: string;');
lines.push('}');
lines.push('');
lines.push('export const SKILLS_EMBED: EmbeddedSkill[] = [');
for (const p of packs) {
  const m = p.meta;
  lines.push('  {');
  lines.push('    body: ' + q(p.body) + ',');
  lines.push('    meta: {');
  lines.push('      id: ' + q(m.id) + ',');
  lines.push('      version: ' + q(m.version) + ',');
  lines.push('      name: ' + q(m.name) + ',');
  lines.push('      cls: ' + q(m.cls) + ',');
  lines.push('      family: ' + q(m.family) + ',');
  lines.push('      requires: ' + list(m.requires || []) + ',');
  lines.push('      questions: ' + list(m.questions || []) + ',');
  lines.push('      false_positives: ' + list(m.false_positives || []) + ',');
  lines.push('      poc_must_show: ' + list(m.poc_must_show || []) + ',');
  lines.push('      impact_bar: ' + q(m.impact_bar) + ',');
  lines.push('    },');
  lines.push('  },');
}
lines.push('];');
lines.push('');

writeFileSync(out, lines.join('\n'));
console.log('wrote ' + out + ' with ' + packs.length + ' embedded skill(s)');
